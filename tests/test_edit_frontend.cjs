const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const file = path.join(__dirname, '../static/edit.js');
assert.ok(fs.existsSync(file), 'edit page controller must exist');
const nodes = {};
const context = {window: {}, $: id => nodes[id] ||= {checked:true,disabled:false,textContent:''}, clearTimeout(){}};
vm.createContext(context); vm.runInContext(fs.readFileSync(file, 'utf8'), context);
const canvas = {getBoundingClientRect:()=>({left:10,top:20,width:512,height:384})};
const point = context.editPixelPoint({clientX:266,clientY:212}, canvas, {width:1024,height:768});
assert.deepEqual(JSON.parse(JSON.stringify(point)), {x:512,y:384}, 'points must use original pixels rather than display pixels');
vm.runInContext("editState.maskJob = 'old'; editState.ready = true; editInvalidate();", context);
assert.equal(nodes['edit-confirm'].checked,false, 'changing selection must revoke confirmation');
assert.equal(nodes['edit-render'].disabled,true, 'changing selection must prohibit rendering an old mask');
assert.equal(vm.runInContext('editState.maskJob', context),null);
assert.equal(typeof context.editLatestJob,'function','edit page must choose the latest operation on refresh');
assert.equal(context.editLatestJob({render_job_id:'old',selection_job_id:'new',latest_job_id:'new'}),'new','refresh must resume the latest selection instead of an older render');
context.api=()=>new Promise(()=>{});
vm.runInContext('editState.busy=false; editState.opening=false;',context);
context.editOpenJob({edit_id:'session',id:'job'});
assert.equal(vm.runInContext('editState.busy',context),true,'history must lock before its first asynchronous request');
console.log('Edit source-coordinate and confirmation tests passed');
const app=fs.readFileSync(path.join(__dirname,'../static/app.js'),'utf8');
const apiSource=app.slice(app.indexOf('async function api('),app.indexOf('function action('));
const apiContext={state:{token:'test'},fetch:async()=>({ok:false,status:404,json:async()=>{throw new Error('HTML error response');}})};
vm.createContext(apiContext);vm.runInContext(apiSource,apiContext);
(async()=>{
  await assert.rejects(apiContext.api('jobs/missing'),error=>error.status===404,'missing history records must be identifiable');
  context.api=async()=>{const error=new Error('missing');error.status=404;throw error;};
  assert.equal(await context.editOptionalJob('deleted-selection'),null,'deleted selection must not block render history');
  context.api=async()=>{const error=new Error('offline');error.status=503;throw error;};
  await assert.rejects(context.editOptionalJob('job'),error=>error.status===503,'real service failures must remain visible');
  context.toast=()=>{};
  vm.runInContext("editState.busy=false;editState.job='old';editState.opening=false;",context);
  await context.editAction(async()=>{throw new Error('invalid request');});
  assert.equal(vm.runInContext('editState.busy',context),false,'failed requests must unlock controls even when an older task exists');
  console.log('Missing-record recovery and failure unlock tests passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
